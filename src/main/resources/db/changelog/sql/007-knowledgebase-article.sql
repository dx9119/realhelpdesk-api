-- Справочник категорий базы знаний.
-- Обязательно должен совпадать с KnowledgeBaseCategoryModel:
--     id, name, description, created_at, version
--
-- Создается первым: статья ссылается по category_id, поэтому FK
-- не может указывать на несуществующую таблицу.

-- ---------------------------------------------------------------------------
-- Категории базы знаний
-- ---------------------------------------------------------------------------

CREATE TABLE knowledgebase_categories (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    name          VARCHAR(100) NOT NULL,
    description   TEXT,
    created_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    version       INTEGER NOT NULL,
    CONSTRAINT knowledgebase_categories_pkey PRIMARY KEY (id)
);

-- Уникальность регистронезависимая: «Оплата» и «оплата» — одна категория.
-- Обычный UNIQUE (name) такое не ловит, поэтому индекс по lower(name).
CREATE UNIQUE INDEX knowledgebase_categories_name_lower_key ON knowledgebase_categories (lower(name));

-- ---------------------------------------------------------------------------
-- Статьи базы знаний
-- ---------------------------------------------------------------------------

CREATE TABLE knowledgebase_articles (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY,
    question      VARCHAR(500) NOT NULL,
    answer        TEXT NOT NULL,
    category_id   BIGINT NOT NULL,
    portal_id     BIGINT,
    created_at    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    is_deleted    BOOLEAN NOT NULL DEFAULT false,
    time_delete   TIMESTAMP(6) WITH TIME ZONE,
    version       INTEGER NOT NULL,
    CONSTRAINT knowledgebase_articles_pkey PRIMARY KEY (id),
    CONSTRAINT fk_kb_article_category FOREIGN KEY (category_id) REFERENCES knowledgebase_categories (id),
    CONSTRAINT fk_kb_article_portal FOREIGN KEY (portal_id) REFERENCES portals (id) ON DELETE SET NULL
);

CREATE INDEX idx_kb_article_category_id ON knowledgebase_articles (category_id);
CREATE INDEX idx_kb_article_portal_id ON knowledgebase_articles (portal_id);
CREATE INDEX idx_kb_article_created_at ON knowledgebase_articles (created_at);
